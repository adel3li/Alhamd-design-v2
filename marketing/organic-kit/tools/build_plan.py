def kind_of(cid: str) -> str:
    if cid.startswith(("RL", "NR")):
        return "ريل"
    if cid.startswith(("CR", "TR")):
        return "كاروسيل"
    if cid.startswith("SV"):
        return "آية"
    return "منشور"


def caption_for(cid: str, b_today: dict, blessings: dict, verses: dict, live: bool) -> str:
    cta = CTA_LIVE if live else CTA_PRE
    if cid.startswith("NR-"):
        b = blessings[int(cid[3:])]
        return f"{b['title']}… تخيّلها غائبةً لحظة، ثم عُد إليها.\n{b['opening']}\nفي «الحمد» دقيقتان معها كلَّ يوم.\n{cta}"
    if cid.startswith("TR-"):
        b = blessings[int(cid[3:])]
        return f"جرّبها الآن: دقيقتان مع {b['title']}.\nاقرأ كلَّ صفحةٍ ببطء… ثم اسحب.\nهكذا يأخذك «الحمد» كلَّ يوم إلى نعمةٍ واحدة.\n{cta}"
    if cid.startswith("SV-"):
        v = verses[cid]
        return f"جمعةٌ مباركة.\n﴿{v['text']}﴾ [{v['surahName']}: {ar(v['ayah'])}]\n{SV_LINE.get(cid, '')}\nاجعل جمعتك جمعةَ حمد."
    if cid.startswith("CD-") and cid != "CD-0" and cid not in CAP:
        n = int(cid[3:])
        return f"{ar(n)} أيام… ويصل «الحمد» إلى Google Play.\nفعّل التنبيهات."
    base = CAP.get(cid, "")
    if "﴿وَلَعَلَّكُمْ تَشْكُرُونَ﴾" in base and "SV-13" in verses:  # quote the verified text, never a retyped one
        base = base.replace("﴿وَلَعَلَّكُمْ تَشْكُرُونَ﴾", "﴿" + " ".join(verses["SV-13"]["text"].split()[-2:]) + "﴾ [البقرة: ١٨٥]")
    if cid in ("CD-0", "RL-08", "PS-34", "PS-37", "PS-36", "CR-06"):
        return base
    return f"{base}\n{cta}" if base else cta


