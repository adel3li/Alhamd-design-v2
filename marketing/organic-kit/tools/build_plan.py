def load_kit():
    js = (ROOT / "kit" / "content.js").read_text(encoding="utf-8")
    content = json.loads(js[js.index("=") + 1:].strip().rstrip(";"))
    stills = json.loads((ROOT / "out" / "stills" / "meta.json").read_text(encoding="utf-8")) if (ROOT / "out" / "stills" / "meta.json").exists() else {}
    reels = json.loads((ROOT / "out" / "reels" / "meta.json").read_text(encoding="utf-8")) if (ROOT / "out" / "reels" / "meta.json").exists() else {}
    return content, stills, reels


def app_blessing(d: dt.date, blessings: list) -> dict:
    pool = sorted([b for b in blessings if b["id"] != "islam"], key=lambda b: b["n"])
    return pool[(d - dt.date(1970, 1, 1)).days % len(pool)]


