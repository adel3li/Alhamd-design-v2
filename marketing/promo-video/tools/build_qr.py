"""
Writes scenes/qr.js: a QR code for https://alhamd.app as one SVG path in module units.

  pip install segno
  python3 tools/build_qr.py [url]
"""
import sys
from pathlib import Path

import segno

ROOT = Path(__file__).resolve().parent.parent
url = sys.argv[1] if len(sys.argv) > 1 else "https://alhamd.app"
rows = list(segno.make(url, error="m", micro=False).matrix)
n = len(rows)
parts = []
for y, row in enumerate(rows):
    x = 0
    while x < n:
        if row[x]:
            start = x
            while x < n and row[x]:
                x += 1
            parts.append(f"M{start},{y}h{x - start}v1h-{x - start}z")
        else:
            x += 1
(ROOT / "scenes" / "qr.js").write_text(
    f"/* QR code for {url} (generated by tools/build_qr.py; error correction M). */\n"
    f"window.QR = {{ size: {n}, path: '{''.join(parts)}' }};\n",
    encoding="utf-8",
)
print(f"scenes/qr.js: {n}×{n} modules for {url}")
