def find(coll, num):
    out = []
    for h in H[coll]:
        if coll == 'muslim':
            an = str(h.get('arabicnumber', ''))
            if an and an.split('.')[0] == str(num):
                out.append(h)
        elif str(h.get('hadithnumber')) == str(num) or str(h.get('arabicnumber')) == str(num):
            out.append(h)
    return out

