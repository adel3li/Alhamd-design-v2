def norm(s):
    s = unicodedata.normalize('NFD', s)
    s = re.sub('[ؐ-ًؚ-ٰٟۖ-ۭ࣓-ࣣ࣡-ࣿـ‏‎]', '', s)
    s = re.sub('[آأإٱ-ٳٵ]', 'ا', s)
    s = re.sub('[ىی]', 'ي', s).replace('ة', 'ه').replace('ؤ', 'و').replace('ئ', 'ي')
    s = re.sub(r'[^\w\s]', ' ', s)
    return ' ' + re.sub(r'\s+', ' ', s).strip() + ' '

