export const getDailyHisnTip = (date: Date = new Date()): { tip: HisnDailyTip; index: number } => {
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = Math.abs(dayOfYear) % HISN_DAILY_TIPS.length;
  return { tip: HISN_DAILY_TIPS[index], index };
};

